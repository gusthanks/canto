#!/usr/bin/env bash
set -euo pipefail

# Runs the same six gates as the canto-quality CI workflow:
#   rustfmt       cargo fmt --all -- --check
#   blueprints    ./scripts/checks/lint-blueprints.sh
#   shellcheck    shellcheck on every .sh file and on scripts/hooks/*
#   icons         ./scripts/checks/check-icons.sh
#   translations  ./scripts/checks/check-translations.sh
#   docrefs       ./scripts/checks/check-doc-refs.py (names in the docs exist)
#
# Usage: ./scripts/checks/check-quality.sh [gate...]   (default: all six)
# A gate whose tool is missing fails; name the other gates to run only those.

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO_ROOT"

ALL_GATES=(rustfmt blueprints shellcheck icons translations docrefs)

gate_rustfmt() {
    # config.rs is generated by meson; create an empty placeholder if missing.
    if [[ ! -f src/config.rs ]]; then
        echo "(creating empty src/config.rs placeholder)"
        echo > src/config.rs
    fi
    if ! command -v cargo &>/dev/null; then
        echo "cargo not found."
        return 1
    fi
    cargo fmt --all -- --check || { echo "Run 'cargo fmt --all' to fix."; return 1; }
}

gate_blueprints() {
    ./scripts/checks/lint-blueprints.sh
}

gate_shellcheck() {
    if ! command -v shellcheck &>/dev/null; then
        echo "shellcheck not found, install it to run this gate."
        return 1
    fi
    local files=()
    while IFS= read -r -d '' f; do
        files+=("$f")
    done < <(find . \( -path ./cargo -o -path ./target -o -path ./build -o -path ./.git \) -prune \
        -o -type f \( -name "*.sh" -o -path "./scripts/hooks/*" \) -print0)
    shellcheck "${files[@]}"
}

gate_icons() {
    ./scripts/checks/check-icons.sh
}

gate_translations() {
    ./scripts/checks/check-translations.sh
}

gate_docrefs() {
    if ! command -v python3 &>/dev/null; then
        echo "python3 not found."
        return 1
    fi
    python3 -I ./scripts/checks/check-doc-refs.py
}

gates=("$@")
[[ ${#gates[@]} -eq 0 ]] && gates=("${ALL_GATES[@]}")

for gate in "${gates[@]}"; do
    if ! declare -F "gate_$gate" >/dev/null; then
        echo "Unknown gate: $gate (known: ${ALL_GATES[*]})" >&2
        exit 2
    fi
done

passed=()
failed=()
for gate in "${gates[@]}"; do
    echo "=== $gate ==="
    if "gate_$gate"; then
        echo "PASS: $gate"
        passed+=("$gate")
    else
        echo "FAIL: $gate"
        failed+=("$gate")
    fi
    echo ""
done

if [[ ${#failed[@]} -ne 0 ]]; then
    echo "Quality checks failed: ${failed[*]} (passed ${#passed[@]} of ${#gates[@]})."
    exit 1
fi
echo "All ${#gates[@]} quality gates passed: ${passed[*]}."
